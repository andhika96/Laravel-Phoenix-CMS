	function normalize(node) {
		const settings = { ...defaults(), ...(node.settings || {}) };
		if (TYPE === 'container_fluid') settings.contentWidth = 'fluid';
		if (settings.customCss && !settings.cssClass) settings.cssClass = settings.customCss;
		settings.animateWithAI = false;
		settings.attributes = Array.isArray(settings.attributes) ? settings.attributes : [];
		settings.bgSlideshowImages = Array.isArray(settings.bgSlideshowImages)
			? settings.bgSlideshowImages.filter((image) => image && typeof image.url === 'string' && image.url.trim())
			: [];
		node.settings = settings;
		return node;
	}

