import assert from 'node:assert/strict';
import { chromium } from 'playwright-core';
import { writeFile } from 'node:fs/promises';
const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
const context=await browser.newContext({ignoreHTTPSErrors:true,viewport:{width:390,height:844}});
const page=await context.newPage();
const base='https://laravel-13-phoenix.aruna', results=[];
try {
 await page.goto(base+'/login',{waitUntil:'domcontentloaded'});
 await page.locator('[name=email]').fill(process.env.CMS_MODAL_EMAIL);
 await page.locator('[name=password]').fill(process.env.CMS_MODAL_PASSWORD);
 await page.locator('[type=submit]').click();
 await page.waitForURL(url=>!url.pathname.includes('login'),{waitUntil:'domcontentloaded'});
 await page.route('**/*',route=>['POST','PUT','PATCH','DELETE'].includes(route.request().method())?route.abort():route.continue());
 await page.goto(base+'/manage_event',{waitUntil:'domcontentloaded'});
 await page.waitForFunction(()=>!!window.bootstrap);
 await page.evaluate(()=>bootstrap.Modal.getOrCreateInstance(document.getElementById('eventDeleteModal')).show());
 await page.waitForTimeout(650);
 await page.locator('#eventDeleteModal').getByRole('button',{name:'No, keep it',exact:true}).click();
 await page.waitForTimeout(500);
 assert.equal(await page.locator('#eventDeleteModal').evaluate(el=>el.classList.contains('show')),false);
 results.push('Event cancellation button dismisses confirmation');
 await page.goto(base+'/awesome_admin/header-navigation',{waitUntil:'domcontentloaded'});
 await page.evaluate(()=>document.getElementById('headerEditorExitDialog').showModal());
 await page.keyboard.press('Escape');
 assert.equal(await page.locator('#headerEditorExitDialog').evaluate(el=>el.open),false);
 results.push('Escape closes Header Navigation dialog');
 await page.goto(base+'/manage_article/templates',{waitUntil:'domcontentloaded'});
 await page.locator('#article-template-options-trigger').click();
 await page.waitForTimeout(650);
 await page.evaluate(()=>{window.ManageArticleTemplateVue3.optionsModal.value.header.title.text+=' QC';});
 await page.waitForTimeout(100);
 await page.evaluate(()=>window.ManageArticleTemplateVue3.requestCloseTemplateOptions());
 await page.waitForTimeout(150);
 assert.equal(await page.locator('.article-template-discard-dialog').evaluate(el=>el.open),true);
 await page.keyboard.press('Escape');
 assert.equal(await page.locator('.article-template-discard-dialog').evaluate(el=>el.open),false);
 assert.equal(await page.locator('#modalArticleTemplateOptions').evaluate(el=>el.classList.contains('show')),true);
 assert.equal(await page.evaluate(()=>window.ManageArticleTemplateVue3.optionsModal.dirty),true);
 results.push('Escape keeps Template Options open with unsaved draft intact');
 await page.evaluate(()=>window.ManageArticleTemplateVue3.discardTemplateOptions());
 await page.waitForTimeout(550);
 assert.equal(await page.evaluate(()=>document.activeElement?.id),'article-template-options-trigger');
 results.push('Closing Template Options restores focus to opener');
 await page.goto(base+'/workflow/create',{waitUntil:'domcontentloaded'});
 await page.waitForFunction(()=>!!window.WorkflowEditorVue);
 await page.evaluate(async()=>{const app=window.WorkflowEditorVue;app.addNode('icon');await app.openIconPicker(app.selectedNode);});
 await page.keyboard.press('Escape');
 await page.waitForTimeout(100);
 assert.equal(await page.locator('.workflow-icon-dialog').count(),0);
 await page.evaluate(()=>window.WorkflowEditorVue.dirty=false);
 results.push('Escape closes Workflow picker');
 await writeFile(new URL('./keyboard-results.json',import.meta.url),JSON.stringify(results,null,2));
 console.log(JSON.stringify({passed:results.length,results},null,2));
} finally {await browser.close();}
