import fs from 'node:fs';
import assert from 'node:assert/strict';
const dir='project-artifacts/plans/cms-css-framework-switch-20261103';
const audit=JSON.parse(fs.readFileSync(dir+'/component-audit.json','utf8'));
const result=JSON.parse(fs.readFileSync(dir+'/browser-inventory.json','utf8').replace(/^\uFEFF/,''));
assert(!result.isError,result.error);
const runtime=JSON.parse(result.result);
assert.equal(audit.viewCount,65);assert.equal(audit.scriptCount,28);
assert.equal(audit.bootstrapApi.length,239);assert.equal(audit.bootstrapEvents.length,78);
assert.equal(runtime.pages.length,12);assert(runtime.pages.every(row=>row.status===200));assert.equal(runtime.errors.length,0);
for(const file of audit.files)assert(fs.existsSync(file),file);
for(const file of ['PLAN.md','COMPONENT-MATRIX.md','ACCEPTANCE-CHECKLIST.md'])assert(fs.statSync(dir+'/'+file).size>1000);
const plan=fs.readFileSync(dir+'/PLAN.md','utf8');
for(let gate=0;gate<=6;gate++)assert(plan.includes(`### G${gate}`));
const checklist=fs.readFileSync(dir+'/ACCEPTANCE-CHECKLIST.md','utf8');
const ids=[...checklist.matchAll(/^- \[ \] ([A-Z]+-\d+)/gm)].map(match=>match[1]);
assert.equal(ids.length,new Set(ids).size);assert(ids.length>=65);
const matrix=fs.readFileSync(dir+'/COMPONENT-MATRIX.md','utf8');
for(const name of Object.keys(audit.categories))assert(matrix.includes('| '+name+' |'));
console.log(JSON.stringify({sourceViews:audit.viewCount,sourceScripts:audit.scriptCount,bootstrapReferences:audit.bootstrapApi.length,eventReferences:audit.bootstrapEvents.length,runtimePages:runtime.pages.length,runtimePageErrors:runtime.errors.length,plannedAcceptanceCases:ids.length,phaseGates:7,planArtifactsVerified:true},null,2));
